// Bundles the community Edge Function (handler + shared prompts) into one file that can be pasted into the
// Supabase dashboard editor or deployed with the Supabase CLI: supabase/functions/community/index.ts
// Run: node scripts/build-community.mjs   (also writes a Node-testable copy when given --test <outfile>)
import { build } from 'esbuild';
import { fileURLToPath } from 'url';
import path from 'path';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const test = process.argv.indexOf('--test');
const banner = '// GENERATED by scripts/build-community.mjs from handler.ts, entry.ts and src/core/shared.js. Edit those, then rebuild.\n// deno-lint-ignore-file\n';
if (test > 0) {
  await build({entryPoints: [path.join(root, 'supabase/functions/community/handler.ts')], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', outfile: process.argv[test + 1], logLevel: 'error'});
} else {
  await build({entryPoints: [path.join(root, 'supabase/functions/community/entry.ts')], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', external: ['npm:*'], banner: {js: banner}, outfile: path.join(root, 'supabase/functions/community/index.ts'), logLevel: 'error'});
}
console.log('built', test > 0 ? process.argv[test + 1] : 'supabase/functions/community/index.ts');
