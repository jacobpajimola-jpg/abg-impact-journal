// Bundles the canva Edge Function (handler + entry) into one file that can be pasted into the Supabase dashboard
// editor or deployed with the Supabase CLI: supabase/functions/canva/index.ts
// Run: node scripts/build-canva.mjs   (--test <outfile> writes a Node-testable copy of the handler)
import { build } from 'esbuild';
import { fileURLToPath } from 'url';
import path from 'path';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const test = process.argv.indexOf('--test');
const banner = '// GENERATED by scripts/build-canva.mjs from handler.ts and entry.ts. Edit those, then rebuild.\n// deno-lint-ignore-file\n';
if (test > 0) {
  await build({entryPoints: [path.join(root, 'supabase/functions/canva/handler.ts')], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', outfile: process.argv[test + 1], logLevel: 'error'});
} else {
  await build({entryPoints: [path.join(root, 'supabase/functions/canva/entry.ts')], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', external: ['npm:*'], banner: {js: banner}, outfile: path.join(root, 'supabase/functions/canva/index.ts'), logLevel: 'error'});
}
console.log('built', test > 0 ? process.argv[test + 1] : 'supabase/functions/canva/index.ts');
